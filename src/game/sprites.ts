// Color mapping for sprite strings
const COLOR_MAP: Record<string, string> = {
  '.': '', // transparent
  '0': PALETTE.black,
  '1': PALETTE.darkBlue,
  '2': PALETTE.darkPurple,
  '3': PALETTE.darkGreen,
  '4': PALETTE.brown,
  '5': PALETTE.darkGray,
  '6': PALETTE.lightGray,
  '7': PALETTE.white,
  '8': PALETTE.red,
  '9': PALETTE.orange,
  'a': PALETTE.yellow,
  'b': PALETTE.green,
  'c': PALETTE.blue,
  'd': PALETTE.indigo,
  'e': PALETTE.pink,
  'f': PALETTE.peach,
};

// Sprite cache
const spriteCache: Map<string, HTMLCanvasElement> = new Map();

// Convert a string grid sprite to a canvas
function spriteToCanvas(rows: string[], pixelSize: number = 1): HTMLCanvasElement {
  const h = rows.length;
  const w = rows[0].length;
  const canvas = document.createElement('canvas');
  canvas.width = w * pixelSize;
  canvas.height = h * pixelSize;
  const ctx = canvas.getContext('2d')!;
  ctx.imageSmoothingEnabled = false;

  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      const ch = rows[y][x];
      const color = COLOR_MAP[ch];
      if (color) {
        ctx.fillStyle = color;
        ctx.fillRect(x * pixelSize, y * pixelSize, pixelSize, pixelSize);
      }
    }
  }
  return canvas;
}

